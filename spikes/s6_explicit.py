"""Spike S6: accuracy of the explicit check (D7, step 11) on hand-labelled dialog excerpts.

Runs the production `check_explicit` (src/gut_zu_wissen/explicit.py) with the judge model from
config/pipeline.toml on every case REPEATS times and evaluates the flag against the labels.

Usage (ANTHROPIC_API_KEY in the environment, e.g. `set -a; . ./.env; set +a`):
  uv run --group spikes python spikes/s6_explicit.py revids   # fill in revids (Wikipedia API)
  uv run --group spikes python spikes/s6_explicit.py sheet    # write the labelling sheet
  uv run --group spikes python spikes/s6_explicit.py run      # live calls, results JSON
  uv run --group spikes python spikes/s6_explicit.py report   # evaluate the saved results

`report` reads the labels from the cases file each time, so after the labels change it
re-evaluates the saved answers without new calls; `run` is only needed for a prompt change.
"""

import json
import statistics
import sys
import time
import tomllib
from collections import Counter, defaultdict
from concurrent.futures import ThreadPoolExecutor
from datetime import UTC, datetime
from pathlib import Path

import anthropic
import httpx

from gut_zu_wissen.dialog import Turn
from gut_zu_wissen.explicit import EXPLICIT_PROMPT, ExplicitCheck, check_explicit
from gut_zu_wissen.llm import AnthropicLlm, LlmError

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "tests" / "fixtures" / "wikipedia" / "spikes"
CASES = FIXTURES / "s6_cases.json"
RESULTS = FIXTURES / "s6_results"
SHEET = ROOT / "spikes" / "s6_labels.md"
CONFIG = ROOT / "config" / "pipeline.toml"

REPEATS = 3  # calls per case
WORKERS = 4  # parallel requests
# USD per million tokens for claude-sonnet-5-5 (config [prices] is still PLACEHOLDER).
PRICE_IN, PRICE_OUT = 2.00, 10.00

API = "https://de.wikipedia.org/w/api.php"
USER_AGENT = "GutZuWissen/0.1 (spike; gut-zu-wissen@fourteen-it.de)"


def load_cases() -> dict:
    return json.loads(CASES.read_text())


def save_cases(cases: dict) -> None:
    CASES.write_text(json.dumps(cases, ensure_ascii=False, indent=1) + "\n")


def turns_of(item: dict) -> list[Turn]:
    return [Turn(i, speaker, text, []) for i, (speaker, text) in enumerate(item["turns"])]


# ---------------------------------------------------------------- revids


def revids() -> None:
    """Latest sighted revision (D2) of each source article, for the CC BY-SA attribution."""
    cases = load_cases()
    titles = sorted({i["article"] for i in cases["items"]})
    found: dict[str, int] = {}
    with httpx.Client(headers={"User-Agent": USER_AGENT}, timeout=30) as client:
        for title in titles:
            r = client.get(
                API,
                params={
                    "action": "query",
                    "prop": "info|flagged",
                    "titles": title,
                    "redirects": "1",
                    "format": "json",
                    "formatversion": "2",
                    "maxlag": "5",
                },
            )
            r.raise_for_status()
            page = r.json()["query"]["pages"][0]
            if page.get("missing"):
                print(f"MISSING: {title}")
                continue
            flagged = page.get("flagged") or {}
            found[title] = flagged.get("stable_revid", page["lastrevid"])
            print(f"{title}: {found[title]}")
            time.sleep(1)
    for item in cases["items"]:
        item["revid"] = found.get(item["article"], item["revid"])
    save_cases(cases)


# ---------------------------------------------------------------- sheet


def sheet() -> None:
    cases = load_cases()
    lines = [
        "# Spike S6: labelling sheet (proposal, to be confirmed)",
        "",
        "Generated by `spikes/s6_explicit.py sheet` from",
        "[s6_cases.json](../tests/fixtures/wikipedia/spikes/s6_cases.json); do not edit here.",
        "",
        "Rule (2026-11-19): explicit only for a *drastic* depiction of violence, sexuality or",
        "drugs (vivid, detailed or sensational, glorifying, or instructions), or spoken",
        "profanity. A factual, historical, scientific or passing mention does not count.",
        "",
        "**To confirm or correct:** in `s6_cases.json`, per item set `expected` to `explicit`",
        "or `clean` and `confirmed` to `true`. Then run `sheet` and `report` again (no API",
        "calls needed). Or just reply with the IDs to flip.",
        "",
        "| ID | Article | Intent | Proposed | Why | Your label |",
        "|---|---|---|---|---|---|",
    ]
    for item in cases["items"]:
        mine = item["expected"] if item["confirmed"] else ""
        lines.append(
            f"| {item['id']} | {item['article']} | {item['group']}/{item['category']} | "
            f"{item['expected']} | {item['rationale']} | {mine} |"
        )
    lines.append("")
    for group in ("clean", "borderline", "explicit"):
        lines += [f"## {group}", ""]
        for item in (i for i in cases["items"] if i["group"] == group):
            mark = "confirmed" if item["confirmed"] else "proposed"
            lines.append(
                f"### {item['id']} · {item['article']} · {item['category']} → "
                f"**{item['expected']}** ({mark})"
            )
            lines += ["", f"*{item['rationale']}*", ""]
            lines += [f"> **{s}:** {t}  " for s, t in item["turns"]]
            lines.append("")
    SHEET.write_text("\n".join(lines))
    print(f"wrote {SHEET.relative_to(ROOT)}")


# ---------------------------------------------------------------- run


class RecordingClient:
    """Wraps the SDK client so the spike sees usage and latency; the request is unchanged."""

    def __init__(self) -> None:
        self._client = anthropic.Anthropic()
        self.messages = self
        self.last: dict = {}

    def create(self, **kwargs):
        started = time.perf_counter()
        response = self._client.messages.create(**kwargs)
        self.last = {
            "seconds": round(time.perf_counter() - started, 3),
            "input_tokens": response.usage.input_tokens,
            "output_tokens": response.usage.output_tokens,
            "stop_reason": response.stop_reason,
        }
        return response


def one_call(model: str, max_tokens: int, item: dict, rep: int) -> dict:
    client = RecordingClient()
    llm = AnthropicLlm(model, max_tokens, client=client)
    record = ExplicitCheck(model=model)
    try:
        check_explicit(record, llm, turns_of(item))
    except LlmError as exc:
        record.error = str(exc)
    return {"id": item["id"], "repeat": rep, **client.last, "check": record.to_dict()}


def run() -> None:
    config = tomllib.loads(CONFIG.read_text())
    model = config["models"]["llm_judge"]
    max_tokens = config["quotas"]["llm_max_tokens"]
    items = load_cases()["items"]
    jobs = [(item, rep) for rep in range(REPEATS) for item in items]
    with ThreadPoolExecutor(WORKERS) as pool:
        records = list(pool.map(lambda j: one_call(model, max_tokens, *j), jobs))
    RESULTS.mkdir(parents=True, exist_ok=True)
    out = RESULTS / f"{model}.json"
    payload = {
        "model": model,
        "max_tokens": max_tokens,
        "repeats": REPEATS,
        "run_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "prompt": EXPLICIT_PROMPT,
        "records": records,
    }
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n")
    print(f"{out.relative_to(ROOT)}: {len(records)} calls")


# ---------------------------------------------------------------- report


def pct(n: int, d: int) -> str:
    return f"{n}/{d} ({100 * n / d:.0f} %)" if d else "0/0"


def report() -> None:
    items = {i["id"]: i for i in load_cases()["items"]}
    for path in sorted(RESULTS.glob("*.json")):
        data = json.loads(path.read_text())
        records = data["records"]
        ok = [r for r in records if not r["check"]["error"]]
        errors = [r for r in records if r["check"]["error"]]
        print(f"\n=== {path.stem}  calls={len(records)}  errors={len(errors)}")
        for r in errors:
            print(f"  ERROR {r['id']}#{r['repeat']}: {r['check']['error']}")

        def is_fp(r: dict) -> bool:
            return items[r["id"]]["expected"] == "clean" and r["check"]["explicit"]

        def is_fn(r: dict) -> bool:
            return items[r["id"]]["expected"] == "explicit" and not r["check"]["explicit"]

        clean_runs = [r for r in ok if items[r["id"]]["expected"] == "clean"]
        expl_runs = [r for r in ok if items[r["id"]]["expected"] == "explicit"]
        unc = [r for r in ok if r["check"]["verdict"] == "uncertain"]
        verdict_ne_flag = [
            r for r in ok if (r["check"]["verdict"] == "explicit") != r["check"]["explicit"]
        ]
        fps, fns = sum(map(is_fp, clean_runs)), sum(map(is_fn, expl_runs))
        print(f"  false positive (clean -> explicit): {pct(fps, len(clean_runs))}")
        print(f"  false negative (explicit -> clean): {pct(fns, len(expl_runs))}")
        print(f"  verdict uncertain:                  {pct(len(unc), len(ok))}")
        print(f"  flag differs from verdict:          {len(verdict_ne_flag)}")
        verdicts = Counter((items[r["id"]]["group"], r["check"]["verdict"]) for r in ok)
        print(f"  verdicts by group: {dict(sorted(verdicts.items()))}")

        print("  per group / category (runs flagged explicit):")
        cells: dict = defaultdict(list)
        for r in ok:
            it = items[r["id"]]
            cells[(it["group"], it["category"])].append(r["check"]["explicit"])
        for (group, cat), flags in sorted(cells.items()):
            print(f"    {group:10} {cat:10} {pct(sum(flags), len(flags))}")

        by_item: dict = defaultdict(list)
        for r in ok:
            by_item[r["id"]].append(r)
        stable_flag = sum(len({r["check"]["explicit"] for r in rs}) == 1 for rs in by_item.values())
        stable_verdict = sum(
            len({r["check"]["verdict"] for r in rs}) == 1 for rs in by_item.values()
        )
        print(f"  stable flag across repeats:    {pct(stable_flag, len(by_item))}")
        print(f"  stable verdict across repeats: {pct(stable_verdict, len(by_item))}")

        print("  misclassified (any repeat):")
        for iid, rs in sorted(by_item.items()):
            wrong = [r for r in rs if is_fp(r) or is_fn(r)]
            if not wrong:
                continue
            it = items[iid]
            print(
                f"    {iid} {it['article']} ({it['group']}/{it['category']}, "
                f"expected {it['expected']}): wrong {len(wrong)}/{len(rs)}"
            )
            for r in wrong:
                c = r["check"]
                print(f"      #{r['repeat']} verdict={c['verdict']} reason: {c['reason']}")
                for f in c["findings"]:
                    print(
                        f"         finding {f['category']} t{f['turn_index']}: "
                        f"„{f['quote']}“ – {f['reason']}"
                    )

        secs = [r["seconds"] for r in ok if "seconds" in r]
        tin = sum(r.get("input_tokens", 0) for r in records)
        tout = sum(r.get("output_tokens", 0) for r in records)
        cost = (tin * PRICE_IN + tout * PRICE_OUT) / 1e6
        print(
            f"  latency median={statistics.median(secs):.1f}s max={max(secs):.1f}s; "
            f"tokens in={tin} out={tout} (per call {tin // len(records)}/{tout // len(records)}); "
            f"cost ${cost:.2f} total, ${cost / len(records):.4f} per call"
        )


if __name__ == "__main__":
    {"revids": revids, "sheet": sheet, "run": run, "report": report}[sys.argv[1]]()
